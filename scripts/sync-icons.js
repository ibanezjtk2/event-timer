// Writes web/js/icons.js from an unpacked @phosphor-icons/core package.
// Only the icons the app uses are copied, as inline SVG paths (no CDN, no icon font).
//   1. download https://registry.npmjs.org/@phosphor-icons/core/-/core-2.1.1.tgz and unpack it
//   2. node scripts/sync-icons.js <unpacked>/package
'use strict';
const fs = require('fs');
const path = require('path');

// app name → Phosphor name. Fixed mapping, see the icon table of the ui-design standard.
const BOLD = {
  play: 'play', pause: 'pause', stop: 'stop', reset: 'arrow-counter-clockwise',
  gear: 'gear-six', plus: 'plus', minus: 'minus', up: 'arrow-up', down: 'arrow-down',
  trash: 'trash', edit: 'pencil-simple', open: 'arrow-square-out', copy: 'copy',
  next: 'skip-forward', prev: 'skip-back', go: 'arrow-right', back: 'arrow-left',
  full: 'arrows-out', 'full-off': 'arrows-in', close: 'x', bell: 'bell', screen: 'monitor',
  talk: 'chat-text', broadcast: 'broadcast', check: 'check', eye: 'eye', 'eye-off': 'eye-slash',
  clock: 'clock', timer: 'timer', list: 'list', info: 'info', warning: 'warning',
  error: 'x-circle', ok: 'check-circle', lock: 'lock', unlock: 'lock-open', help: 'question',
  keyboard: 'keyboard', qr: 'qr-code', connected: 'plugs-connected', disconnected: 'plugs',
  sound: 'speaker-high', mute: 'speaker-slash', save: 'floppy-disk', export: 'download-simple',
  import: 'upload-simple', folder: 'folder-open', more: 'dots-three-vertical',
  'caret-right': 'caret-right', 'caret-down': 'caret-down',
};
// Fill = the active state (running, live, on)
const FILL = ['play', 'pause', 'broadcast', 'eye-off', 'bell', 'talk', 'screen'];

const pkg = process.argv[2];
if (!pkg) {
  console.error('Aufruf: node scripts/sync-icons.js <entpacktes @phosphor-icons/core>/package');
  process.exit(2);
}
const version = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8')).version;
const inner = file => {
  const m = fs.readFileSync(file, 'utf8').match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  if (!m) throw new Error('kein SVG: ' + file);
  return m[1].trim();
};
const out = {};
for (const [k, n] of Object.entries(BOLD)) out[k] = inner(path.join(pkg, 'assets', 'bold', n + '-bold.svg'));
for (const k of FILL) out[k + ':fill'] = inner(path.join(pkg, 'assets', 'fill', BOLD[k] + '-fill.svg'));

const lines = Object.entries(out).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
const js = `/* Phosphor Icons ${version} (MIT, see /licenses/Phosphor-MIT.txt), generated by
   scripts/sync-icons.js – do not edit by hand. Bold = default, ":fill" = active state. */
(function (root) {
  'use strict';
  root.ETIcons = {
${lines.join('\n')}
  };
})(globalThis);
`;
fs.writeFileSync(path.join(__dirname, '..', 'web', 'js', 'icons.js'), js);
console.log(`web/js/icons.js: ${Object.keys(out).length} Icons aus Phosphor ${version}`);
